public class Primitive {
    public static void main(String args[]) {
        // Integer
        float A = 10.0f;
        Double B = 10e-10;

        System.out.println(A);
        System.out.println(B);

        // Integer
        byte a = 10;
        short c = 10;
        int b = 10;
        long d = 10;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
    }
}
